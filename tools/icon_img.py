"""Cuts the supplied pickup sheet (_monsterart/icons_src.webp: 6 x 3 icons on transparency, in the order of KEYS) into js/art/iconimg.js: one small PNG per power-up / tank.
Run: python tools/icon_img.py"""
import base64, io, json, os
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '_monsterart', 'icons_src.webp')
OUT = os.path.join(HERE, '..', 'js', 'art', 'iconimg.js')
KEYS = ['morph', 'missile', 'bombs', 'charge', 'iceBeam', 'heatSuit', 'spaceJump', 'dashBoots', 'waveBeam', 'aquaSuit', 'grapple', 'superMissile',
        'superTank', 'spinFlip', 'scanVisor', 'plasmaBeam', 'energyTank', 'missileTank']
SIZE = 26                                                            # every icon sits in a SIZE x SIZE canvas, bottom-centred
def runs(v):
    out, s = [], None
    for i, x in enumerate(v):
        if x and s is None: s = i
        if not x and s is not None: out.append((s, i - 1)); s = None
    if s is not None: out.append((s, len(v) - 1))
    return out
def png64(img):
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
im = Image.open(SRC).convert('RGBA'); al = np.asarray(im)[..., 3] > 40
cols, rows = runs(al.any(axis=0)), runs(al.any(axis=1)); assert len(cols) == 6 and len(rows) == 3, (len(cols), len(rows))
icons = {}
for ri, (y0, y1) in enumerate(rows):
    for ci, (x0, x1) in enumerate(cols):
        cell = im.crop((x0, y0, x1 + 1, y1 + 1)); s = (SIZE - 1) / float(max(cell.size))
        w, h = max(1, round(cell.width * s)), max(1, round(cell.height * s))
        sc = cell.convert('RGBa').resize((w, h), Image.LANCZOS).convert('RGBA'); a = np.asarray(sc).copy(); a[..., 3] = np.where(a[..., 3] > 110, 255, 0)
        rgb = Image.fromarray(a[..., :3], 'RGB').quantize(colors=32, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB')
        sp = Image.fromarray(np.dstack([np.asarray(rgb), a[..., 3]]), 'RGBA')
        canvas = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0)); canvas.paste(sp, ((SIZE - w) // 2, SIZE - h)); icons[KEYS[ri * 6 + ci]] = png64(canvas)
src = "/* GENERATED by tools/icon_img.py: the power-up and tank icons, one SIZE x SIZE PNG each. */\n(function (G) {\n  G.art = G.art || {};\n  G.art.iconimg = " + json.dumps({'w': SIZE, 'h': SIZE, 'icons': icons}, separators=(',', ':')) + ";\n})((window.SGS = window.SGS || {}));\n"
open(OUT, 'w', encoding='utf-8').write(src); print(len(icons), len(src))
