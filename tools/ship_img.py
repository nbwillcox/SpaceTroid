"""Cuts the supplied landing-ship sheet (_monsterart/ship_src.png: 8 frames on transparency, engine lights pulsing) into js/art/shipimg.js. Run: python tools/ship_img.py"""
import base64, io, json, os
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '_monsterart', 'ship_src.png')
WIDTH = 124                                                    # game pixels across the hull
ROWS = [(215, 416), (695, 896)]; COLS = [(7, 384), (393, 768), (776, 1152), (1160, 1533)]
def quant(img, n=64):
    a = np.asarray(img); alpha = a[..., 3] > 0
    rgb = Image.fromarray(a[..., :3], 'RGB').quantize(colors=n, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB')
    return Image.fromarray(np.dstack([np.asarray(rgb), (alpha * 255).astype(np.uint8)]), 'RGBA')
def png64(img):
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
im = Image.open(SRC).convert('RGBA'); s = WIDTH / 378.0; frames = []
for (y0, y1) in ROWS:
    for (x0, x1) in COLS:
        c = im.crop((x0 - 2, y0 - 2, x1 + 3, y1 + 3)).convert('RGBa').resize((round((x1 - x0 + 5) * s), round((y1 - y0 + 5) * s)), Image.LANCZOS).convert('RGBA')
        a = np.asarray(c).copy(); a[..., 3] = np.where(a[..., 3] > 110, 255, 0); c = Image.fromarray(a, 'RGBA')
        bb = c.getbbox(); frames.append(quant(c.crop(bb)))
W = max(f.width for f in frames); H = max(f.height for f in frames); out = []
for f in frames:
    can = Image.new('RGBA', (W, H), (0, 0, 0, 0)); can.paste(f, ((W - f.width) // 2, H - f.height), f); out.append({'u': png64(can), 'w': W, 'h': H})
src = "/* GENERATED by tools/ship_img.py: the landing ship, 8 frames with pulsing engine lights (feet on the bottom row, centred). */\n(function (G) {\n  G.art = G.art || {};\n  G.art.shipimg = " + json.dumps(out, separators=(',', ':')) + ";\n})((window.SGS = window.SGS || {}));\n"
open(os.path.join(HERE, '..', 'js', 'art', 'shipimg.js'), 'w', encoding='utf-8').write(src); print('wrote', len(src), W, H)
