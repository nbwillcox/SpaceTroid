"""Cuts the supplied landing-ship picture (_monsterart/ship1_src.png, one still image on black) into js/art/shipimg.js: the hull as one PNG plus the positions of its lights
(orange lamps and glowing engine pods, one cyan lamp) so the game can make them pulse. Run: python tools/ship_img.py"""
import base64, io, json, os, math
import numpy as np
from PIL import Image
from collections import deque
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '_monsterart', 'ship1_src.png')
WIDTH = 124                                                    # game pixels across the hull
def components(mask):
    h, w = mask.shape; seen = np.zeros_like(mask, bool); comps = []
    for y in range(h):
        for x in np.nonzero(mask[y] & ~seen[y])[0]:
            if seen[y, x]: continue
            q = deque([(y, int(x))]); seen[y, x] = True; pts = []
            while q:
                cy, cx = q.popleft(); pts.append((cy, cx))
                for dy in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        ny, nx = cy + dy, cx + dx
                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]: seen[ny, nx] = True; q.append((ny, nx))
            comps.append(pts)
    return comps
def fill_holes(g):
    hh, ww = g.shape; out = np.zeros_like(g); q = deque()
    for xx in range(ww):
        for yy in (0, hh - 1):
            if not g[yy, xx] and not out[yy, xx]: out[yy, xx] = True; q.append((yy, xx))
    for yy in range(hh):
        for xx in (0, ww - 1):
            if not g[yy, xx] and not out[yy, xx]: out[yy, xx] = True; q.append((yy, xx))
    while q:
        cy, cx = q.popleft()
        for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            ny, nx = cy + dy, cx + dx
            if 0 <= ny < hh and 0 <= nx < ww and not g[ny, nx] and not out[ny, nx]: out[ny, nx] = True; q.append((ny, nx))
    return ~out
def png64(img):
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
im = Image.open(SRC).convert('RGB'); a = np.asarray(im).astype(int); bg = np.median(a[:6, :6].reshape(-1, 3), axis=0)
m = a.max(2) > 24                                         # the backdrop is black (with faint noise); the hull's darkest outline is navy
comps = components(m); big = max(len(c) for c in comps); mm = np.zeros_like(m)
for c in comps:
    if len(c) >= 0.02 * big:
        for (y, x) in c: mm[y, x] = True
g = mm.copy(); g[1:, :] |= mm[:-1, :]; g[:-1, :] |= mm[1:, :]; g[:, 1:] |= mm[:, :-1]; g[:, :-1] |= mm[:, 1:]; g = fill_holes(g)
ys, xs = np.nonzero(g); x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
rgba = np.dstack([a.astype(np.uint8), (g * 255).astype(np.uint8)])[y0:y1 + 1, x0:x1 + 1]
s = WIDTH / float(x1 - x0 + 1); src = Image.fromarray(rgba, 'RGBA')
w, h = round(src.width * s), round(src.height * s)
sc = src.convert('RGBa').resize((w, h), Image.LANCZOS).convert('RGBA'); b = np.asarray(sc).copy(); b[..., 3] = np.where(b[..., 3] > 110, 255, 0)
rgb = Image.fromarray(b[..., :3], 'RGB').quantize(colors=64, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB')
final = Image.fromarray(np.dstack([np.asarray(rgb), b[..., 3]]), 'RGBA'); b = np.asarray(final).astype(int)
r, gg, bl, al = b[..., 0], b[..., 1], b[..., 2], b[..., 3] > 0
orange = al & (r > 130) & (bl < 120) & (r - bl > 70)
cyan = al & (bl > 190) & (gg > 150) & (r < 140)
RECTS = [('orange', (65, 36, 75, 43)), ('orange', (35, 43, 46, 47)), ('orange', (14, 42, 26, 50)), ('orange', (54, 50, 68, 55)), ('cyan', (85, 43, 99, 48)), ('cyan', (48, 26, 60, 33))]   # where the ship's lights are (game px)
lights = []
for kind, (x0_, y0_, x1_, y1_) in RECTS:
    mk = np.zeros_like(orange); mk[y0_:y1_, x0_:x1_] = (orange if kind == 'orange' else cyan)[y0_:y1_, x0_:x1_]
    pts = [(int(p[1]), int(p[0])) for c in components(mk) if len(c) >= 2 for p in c]
    if pts: lights.append({'k': kind, 'cx': round(sum(p[0] for p in pts) / len(pts), 1), 'cy': round(sum(p[1] for p in pts) / len(pts), 1), 'px': [list(p) for p in pts]})
out = {'u': png64(final), 'w': final.width, 'h': final.height, 'lights': lights}
open(os.path.join(HERE, '..', 'js', 'art', 'shipimg.js'), 'w', encoding='utf-8').write("/* GENERATED by tools/ship_img.py: the landing ship (one still hull) and the pixel positions of its lights. */\n(function (G) {\n  G.art = G.art || {};\n  G.art.shipimg = " + json.dumps(out, separators=(',', ':')) + ";\n})((window.SGS = window.SGS || {}));\n")
print(final.size, [(l['k'], l['cx'], l['cy'], len(l['px'])) for l in lights])
