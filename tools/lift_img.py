"""Cuts the supplied elevator / teleporter arch (_monsterart/lift_src.webp, on transparency) into js/art/liftimg.js: one PNG, the bay (the open space the hero stands in), the deck line
(the glowing disc the hero hops onto) and the pixels of its cyan lights. Run: python tools/lift_img.py"""
import base64, io, json, os
import numpy as np
from PIL import Image
from collections import deque
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '_monsterart', 'lift_src.webp')
BAY_H = 52                                                                 # the bay is sized to house the hero (about 46 px tall)
def png64(img):
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
im = Image.open(SRC).convert('RGBA'); a = np.asarray(im); H, W = a.shape[:2]; opaque = a[..., 3] > 40
ys, xs = np.nonzero(opaque); x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
outside = np.zeros((H, W), bool); q = deque()
for x in range(W):
    for y in (0, H - 1):
        if not opaque[y, x] and not outside[y, x]: outside[y, x] = True; q.append((y, x))
for y in range(H):
    for x in (0, W - 1):
        if not opaque[y, x] and not outside[y, x]: outside[y, x] = True; q.append((y, x))
while q:
    y, x = q.popleft()
    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        ny, nx = y + dy, x + dx
        if 0 <= ny < H and 0 <= nx < W and not opaque[ny, nx] and not outside[ny, nx]: outside[ny, nx] = True; q.append((ny, nx))
hole = ~opaque & ~outside; by, bx = np.nonzero(hole)
# the bay: the biggest enclosed see-through region (rows with a wide run), ignoring the tiny pinholes
rows = [y for y in range(H) if hole[y].sum() > 150]; cols = [x for x in range(W) if hole[:, x].sum() > 150]
bay_src = (min(cols), min(rows), max(cols), max(rows))
s = BAY_H / float(bay_src[3] - bay_src[1] + 1)
src = Image.fromarray(a[y0:y1 + 1, x0:x1 + 1], 'RGBA'); w, h = round(src.width * s), round(src.height * s)
sc = src.convert('RGBa').resize((w, h), Image.LANCZOS).convert('RGBA'); b = np.asarray(sc).copy(); b[..., 3] = np.where(b[..., 3] > 110, 255, 0)
rr, gg, bb = b[..., 0].astype(int), b[..., 1].astype(int), b[..., 2].astype(int); al = b[..., 3] > 0
cyan = al & (bb > 150) & (gg > 130) & (rr < 120) & (bb - rr > 70)
rgb = Image.fromarray(b[..., :3], 'RGB').quantize(colors=64, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB')
qa = np.asarray(rgb).copy(); qa[cyan] = b[..., :3][cyan]
final = Image.fromarray(np.dstack([qa, b[..., 3]]), 'RGBA')
bay = [round((bay_src[0] - x0) * s), round((bay_src[1] - y0) * s), round((bay_src[2] - x0) * s), round((bay_src[3] - y0) * s)]
deck = bay[3] + 3                                                          # where the hero's feet rest: just inside the glowing disc
lights = [[int(x), int(y)] for y, x in zip(*np.nonzero(cyan))]
out = {'u': png64(final), 'w': final.width, 'h': final.height, 'bay': bay, 'deck': deck, 'lights': lights}
open(os.path.join(HERE, '..', 'js', 'art', 'liftimg.js'), 'w', encoding='utf-8').write("/* GENERATED by tools/lift_img.py: the elevator arch, its bay, deck line and cyan light pixels. */\n(function (G) {\n  G.art = G.art || {};\n  G.art.liftimg = " + json.dumps(out, separators=(',', ':')) + ";\n})((window.SGS = window.SGS || {}));\n")
print(final.size, 'bay', bay, 'deck', deck, 'lights', len(lights), 'src bay', bay_src)
from PIL import ImageDraw
bgp = Image.new('RGBA', final.size, (60, 80, 120, 255)); bgp.alpha_composite(final); big = bgp.resize((final.width * 5, final.height * 5), Image.NEAREST); d = ImageDraw.Draw(big)
d.rectangle([bay[0] * 5, bay[1] * 5, bay[2] * 5, bay[3] * 5], outline=(255, 0, 0)); d.line([0, deck * 5, big.width, deck * 5], fill=(0, 255, 0))
big.save(os.path.join(HERE, '..', '_boss_preview', 'lift_preview.png'))
