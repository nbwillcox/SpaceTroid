"""Zone 1 slopes, spikes and breakable blocks -> js/art/zone1misc.js"""
import json, os
from tile_gen1 import W, grid, put, fill_tile

def slope(right):
    """45-degree slope tile: stone below the diagonal, moss draped along it. right=True rises to the right ('/')."""
    base = fill_tile(1)
    g = grid('.')
    for x in range(W):
        lx = x if right else 15 - x
        y0 = 16 - lx if right else 16 - lx   # first solid row for this column (surface y)
        y0 = 16 - lx
        for y in range(max(y0, 0), W):
            g[y][x] = base[y][x]
        if y0 < W:
            for k, c in enumerate(['E' if (x % 4) else 'F', 'D', 'C', 'B']):
                if y0 + k < W and (k < 3 or x % 3 == 0):
                    g[y0 + k][x] = c
            if y0 + 4 < W and g[y0 + 4][x] in '1234':
                g[y0 + 4][x] = '1'
    if not right:
        g = [r[::-1] for r in g]
        # mirror, keeping light from the upper left: flip highlight bias by swapping the lit rim to the new left edge
    return [''.join(r) for r in g]

