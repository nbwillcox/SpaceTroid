def block_shot():
    g = [list(r) for r in fill_tile(2)]
    # sandy crumble block: earth ramp, visible cracks
    ramp = {'1': 'q', '2': 'r', '3': 't', '4': 'u', '5': 'u', 'B': 'r', 'C': 't'}
    g = [[ramp.get(c, c) for c in r] for r in g]
    for (x, y) in [(3, 2), (4, 3), (4, 4), (5, 5), (10, 9), (9, 10), (9, 11), (8, 12), (13, 3), (12, 4)]:
        g[y][x] = 'p'
    return [''.join(r) for r in g]

def block_bomb():
    g = [list(r) for r in fill_tile(0)]
    for (x, y, c) in [(7, 5, 'w'), (8, 5, 'Y'), (6, 6, 'Y'), (7, 6, 'w'), (8, 6, 'Y'), (9, 6, 'y'), (5, 7, 'y'), (6, 7, 'Y'), (7, 7, 'Y'), (8, 7, 'y'), (9, 7, 'y'), (10, 7, 'k'), (6, 8, 'y'), (7, 8, 'y'), (8, 8, 'y'), (9, 8, 'k'), (7, 9, 'k'), (8, 9, 'k')]:
        g[y][x] = c
    return [''.join(r) for r in g]

def block_missile():
    g = grid('m')
    for i in range(W):
        g[0][i] = 'L'; g[15][i] = 'z'; g[i][0] = 'l'; g[i][15] = 'M'
    for i in range(1, 15):
        g[1][i] = 'l'; g[14][i] = 'M'; g[i][1] = 'l'; g[i][14] = 'M'
    for (x, y) in [(2, 2), (13, 2), (2, 13), (13, 13)]:
        g[y][x] = 'z'
    for y in range(4, 12):
        for x in range(4, 12):
            g[y][x] = 'M'
    for k in range(4):   # red-gold chevrons
        for x in (6 + k, 9 - k):
            g[5 + k][x] = 'Y'; g[6 + k][x] = 'y'
    return [''.join(r) for r in g]

