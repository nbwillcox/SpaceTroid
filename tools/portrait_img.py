"""Cuts the supplied detailed hero picture (_monsterart/portrait_src.webp, on transparency) into js/art/portraitimg.js: one PNG for the status screen's portrait (the game tints it per suit).
Run: python tools/portrait_img.py"""
import base64, io, json, os
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '_monsterart', 'portrait_src.webp')
HEIGHT = 168
def png64(img):
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
im = Image.open(SRC).convert('RGBA'); a = np.asarray(im); ys, xs = np.nonzero(a[..., 3] > 40)
im = im.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1)); s = HEIGHT / float(im.height); w, h = round(im.width * s), HEIGHT
sc = im.convert('RGBa').resize((w, h), Image.LANCZOS).convert('RGBA'); b = np.asarray(sc).copy(); b[..., 3] = np.where(b[..., 3] > 120, 255, 0)      # crisp edge, smooth shading
out = Image.fromarray(b, 'RGBA')
open(os.path.join(HERE, '..', 'js', 'art', 'portraitimg.js'), 'w', encoding='utf-8').write("/* GENERATED by tools/portrait_img.py: the status-screen portrait. */\n(function (G) {\n  G.art = G.art || {};\n  G.art.portraitimg = " + json.dumps({'u': png64(out), 'w': w, 'h': h}, separators=(',', ':')) + ";\n})((window.SGS = window.SGS || {}));\n")
print(out.size)
