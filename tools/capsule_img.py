"""Cuts the supplied save capsule picture (_monsterart/capsule_src.webp, on a near-black backdrop) into js/art/capsuleimg.js: one PNG, the glass window (where the save scan lines run) and the
pixels of its cyan lights (which the game makes pulse). Run: python tools/capsule_img.py"""
import base64, io, json, os
import numpy as np
from PIL import Image
from collections import deque
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '_monsterart', 'capsule_src.webp')
GLASS_H = 50                                                             # the glass window is sized to house the hero (about 46 px tall)
def png64(img):
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
im = Image.open(SRC).convert('RGB'); a = np.asarray(im).astype(int); H, W = a.shape[:2]
dark = a.sum(axis=2) < 48                                                   # the backdrop is near-black: flood in from the border
bg = np.zeros((H, W), bool); q = deque()
for x in range(W):
    for y in (0, H - 1):
        if dark[y, x] and not bg[y, x]: bg[y, x] = True; q.append((y, x))
for y in range(H):
    for x in (0, W - 1):
        if dark[y, x] and not bg[y, x]: bg[y, x] = True; q.append((y, x))
while q:
    y, x = q.popleft()
    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        ny, nx = y + dy, x + dx
        if 0 <= ny < H and 0 <= nx < W and dark[ny, nx] and not bg[ny, nx]: bg[ny, nx] = True; q.append((ny, nx))
alpha = ~bg
ys, xs = np.nonzero(alpha); x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
rgba = np.dstack([a.astype(np.uint8), (alpha * 255).astype(np.uint8)])[y0:y1 + 1, x0:x1 + 1]
src = Image.fromarray(rgba, 'RGBA'); s = GLASS_H / 515.0; w, h = round(src.width * s), round(src.height * s)
sc = src.convert('RGBa').resize((w, h), Image.LANCZOS).convert('RGBA'); b = np.asarray(sc).copy(); b[..., 3] = np.where(b[..., 3] > 110, 255, 0)
rr, gg, bb = b[..., 0].astype(int), b[..., 1].astype(int), b[..., 2].astype(int); al = b[..., 3] > 0
cyan = al & (bb > 150) & (gg > 130) & (rr < 120) & (bb - rr > 70)           # lights, glass edge lines
rgb = Image.fromarray(b[..., :3], 'RGB').quantize(colors=64, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB')
qa = np.asarray(rgb).copy(); qa[cyan] = b[..., :3][cyan]
final = Image.fromarray(np.dstack([qa, b[..., 3]]), 'RGBA')
# the glass window: the big teal rectangle (source x 412..675, y 495..1010 inside the cropped picture)
gx0, gx1, gy0, gy1 = (412 - x0) * s, (675 - x0) * s, (495 - y0) * s, (1010 - y0) * s
lights = [[int(x), int(y)] for y, x in zip(*np.nonzero(cyan))]
out = {'u': png64(final), 'w': final.width, 'h': final.height, 'glass': [round(gx0), round(gy0), round(gx1), round(gy1)], 'lights': lights}
open(os.path.join(HERE, '..', 'js', 'art', 'capsuleimg.js'), 'w', encoding='utf-8').write("/* GENERATED by tools/capsule_img.py: the save capsule, its glass window and its cyan light pixels. */\n(function (G) {\n  G.art = G.art || {};\n  G.art.capsuleimg = " + json.dumps(out, separators=(',', ':')) + ";\n})((window.SGS = window.SGS || {}));\n")
print(final.size, 'glass', out['glass'], 'lights', len(lights))
bgp = Image.new('RGBA', final.size, (60, 80, 120, 255)); bgp.alpha_composite(final); bgp.resize((final.width * 6, final.height * 6), Image.NEAREST).save(os.path.join(HERE, '..', '_boss_preview', 'capsule_preview.png'))
