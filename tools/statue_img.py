"""Cuts the supplied shrine statue picture (_monsterart/statue_src.png, on transparency) into js/art/statueimg.js: the big ability statue as one PNG plus the pixels of its
visor and chest jewel, which the game makes glow. Run: python tools/statue_img.py"""
import base64, io, json, os
import numpy as np
from PIL import Image
from collections import deque
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '_monsterart', 'statue_src.png')
HEIGHT = 72
def components(mask):
    h, w = mask.shape; seen = np.zeros_like(mask, bool); comps = []
    for y in range(h):
        for x in np.nonzero(mask[y] & ~seen[y])[0]:
            if seen[y, x]: continue
            q = deque([(y, int(x))]); seen[y, x] = True; pts = []
            while q:
                cy, cx = q.popleft(); pts.append((cy, cx))
                for dy in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        ny, nx = cy + dy, cx + dx
                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]: seen[ny, nx] = True; q.append((ny, nx))
            comps.append(pts)
    return comps
def png64(img):
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
im = Image.open(SRC).convert('RGBA'); bb = im.getchannel('A').point(lambda v: 255 if v > 40 else 0).getbbox(); im = im.crop(bb)
s = HEIGHT / float(im.height); w, h = round(im.width * s), HEIGHT
sc = im.convert('RGBa').resize((w, h), Image.LANCZOS).convert('RGBA'); b = np.asarray(sc).copy(); b[..., 3] = np.where(b[..., 3] > 110, 255, 0)
rgb = Image.fromarray(b[..., :3], 'RGB').quantize(colors=64, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB')
rawrgb = b[..., :3].astype(int); r0, g0, b0 = rawrgb[..., 0], rawrgb[..., 1], rawrgb[..., 2]; alive = b[..., 3] > 0
masks = {'visor': alive & (r0 > 150) & (g0 < 110) & (b0 > 100) & (r0 - g0 > 70), 'jewel': alive & (b0 > 150) & (g0 > 140) & (r0 < 130) & (b0 - r0 > 60)}
qa = np.asarray(rgb).copy()
for m in masks.values(): qa[m] = b[..., :3][m]                      # keep the glow colours out of the 64-colour merge
final = Image.fromarray(np.dstack([qa, b[..., 3]]), 'RGBA')
lights = []
for k, m in masks.items():
    cs = sorted(components(m), key=len, reverse=True)
    if cs and len(cs[0]) >= 4:
        pts = [[int(p[1]), int(p[0])] for p in cs[0]]
        lights.append({'k': k, 'cx': round(sum(p[0] for p in pts) / len(pts), 1), 'cy': round(sum(p[1] for p in pts) / len(pts), 1), 'px': pts})
out = {'u': png64(final), 'w': final.width, 'h': final.height, 'lights': lights}
open(os.path.join(HERE, '..', 'js', 'art', 'statueimg.js'), 'w', encoding='utf-8').write("/* GENERATED by tools/statue_img.py: the big shrine statue and the pixels of its glowing visor and chest jewel. */\n(function (G) {\n  G.art = G.art || {};\n  G.art.statueimg = " + json.dumps(out, separators=(',', ':')) + ";\n})((window.SGS = window.SGS || {}));\n")
print(final.size, [(l['k'], l['cx'], l['cy'], len(l['px'])) for l in lights])
bgp = Image.new('RGBA', final.size, (70, 90, 140, 255)); bgp.alpha_composite(final); big = bgp.resize((final.width * 6, final.height * 6), Image.NEAREST)
from PIL import ImageDraw
d = ImageDraw.Draw(big)
for l in lights:
    for x, y in l['px']: d.rectangle([x * 6, y * 6, x * 6 + 5, y * 6 + 5], outline=(0, 255, 0) if l['k'] == 'visor' else (255, 0, 255))
big.save(os.path.join(HERE, '..', '_boss_preview', 'statue_lights.png'))
